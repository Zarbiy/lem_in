#include "ft_printf.h"

int	ft_putnbr(int n)
{
	char	t;
	int		c;

	c = 0;
	if (n == -2147483648)
	{
		c = 11;
		write(1, "-2147483648", 11);
	}
	else
	{
		if (n < 0)
		{
			c++;
			n = n * -1;
			write(1, "-", 1);
		}
		if (n / 10 != 0)
			c += ft_putnbr(n / 10);
		t = n % 10 + '0';
		write (1, &t, 1);
		c++;
	}
	return (c);
}
